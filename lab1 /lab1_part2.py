print("\n--- ЗАВДАННЯ 9 та 10 ---")
A = int(input("Введіть A: ")) # Менше число
B = int(input("Введіть B (B > A): ")) # Більше число
# Додаємо всі числа в діапазоні від A до B включно (B + 1 потрібно для включення)
sum_AB = sum(i for i in range(A, B + 1)) 
print(f"Сума від A до B: {sum_AB}")
# Те саме, але кожне число підносимо до квадрату (i**2) перед тим як додати
sum_sq_AB = sum(i**2 for i in range(A, B + 1)) 
print(f"Сума квадратів: {sum_sq_AB}")

print("\n--- ЗАВДАННЯ 11 ---")
a_11 = int(input("Введіть a (<= 200): "))
count = 0 # Змінна для підрахунку кількості чисел
total_sum = 0 # Змінна для накопичення загальної суми
for i in range(a_11, 201): # Цикл від введеного 'a' до 200 включно
    total_sum = total_sum + i # Додаємо поточне число до суми
    count = count + 1 # Збільшуємо лічильник чисел на одиницю
# Виводимо середнє (сума поділена на кількість), захищаючись від ділення на нуль
print(f"Середнє арифметичне: {total_sum / count if count > 0 else 0}") 

print("\n--- ЗАВДАННЯ 12 ---")
a_12 = int(input("Введіть a: "))
b_12 = int(input("Введіть b (>= a): "))
sum_while = 0 # Початкова сума
current = a_12 # Поточне значення, яке буде змінюватись
while current <= b_12: # Цикл працює, ПОКИ current менше або дорівнює b
    sum_while += current # Додаємо число до загальної суми
    current += 1 # Обов'язково збільшуємо число на 1, щоб цикл міг завершитись
print(f"Сума (цикл while): {sum_while}")

print("\n--- ЗАВДАННЯ 13 ---")
a_13 = int(input("Введіть a (0 <= a <= 50): "))
# Однорядковий запис: сума всіх квадратів від 'a' до 50 включно
sum_sq_50 = sum(i**2 for i in range(a_13, 51))
print(f"Сума квадратів від a до 50: {sum_sq_50}")

print("\n--- ЗАВДАННЯ 14 ---")
N = int(input("Введіть N (>1): "))
K = 0 # Починаємо з 0-го ступеня
while 5**K <= N: # ПОКИ 5 у ступені K є меншим або рівним N
    K += 1 # Збільшуємо показник ступеня на 1
# Цикл зупиниться, як тільки 5**K стане більше за N
print(f"Найменше K: {K}")

print("\n--- ЗАВДАННЯ 15 ---")
n_15 = int(input("Введіть n: "))
# Перебираємо числа, щоб знайти перше, квадрат якого більший за n
for i in range(1, n_15 + 2):
    if i**2 > n_15: # Умова знайдена
        print(f"Перше число з послідовності квадратів, більше за n: {i**2}")
        break # Команда break зупиняє цикл назавжди після першого ж знаходження

print("\n--- ЗАВДАННЯ 16 ---")
n_16 = int(input("Введіть n: "))
i = 0 # Базове значення для розрахунку формули
val = 1 # Значення першого елементу послідовності (i**2 + 1)
# Використовуємо умову циклу замість оператора if. Цикл йде, поки значення <= n
while val <= n_16: 
    i += 1 # Беремо наступний індекс
    val = i**2 + 1 # Рахуємо нове число за формулою
# Коли значення val перевищить n, цикл завершиться сам
print(f"Перше число з послідовності, більше за n: {val}")