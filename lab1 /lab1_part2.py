print("\n--- ЗАВДАННЯ 8 ---")
num_list = [-5, 10, 3] # Заданий список чисел
# Проходимо циклом по списку. Якщо число > 0, рахуємо його як 1. sum() додає їх.
positives = sum(1 for x in num_list if x > 0) 
