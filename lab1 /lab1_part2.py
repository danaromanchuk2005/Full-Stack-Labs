import math # Підключаємо математичний модуль для роботи з косинусами та синусами

print("--- ЗАВДАННЯ 1 ---")
a, b, c = 0, 2, 4 # Задаємо значення трьом змінним одночасно
# Створюємо новий список: перебираємо числа a, b, c і беремо лише ті, що від 1 до 3
in_interval = [x for x in (a, b, c) if 1 <= x <= 3] 
print(f"Числа з інтервалу [1,3]: {in_interval}") # Виводимо знайдений результат

print("\n--- ЗАВДАННЯ 2 ---")
year = int(input("Введіть рік: ")) # Вводимо рік як ціле число
# Перевірка високосного року: (ділиться на 4 І НЕ ділиться на 100) АБО (ділиться на 400)
if (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0):
    print("Рік високосний: 366 днів") # Якщо умова істинна
else:
    print("Рік звичайний: 365 днів") # Якщо умова хибна

print("\n--- ЗАВДАННЯ 3 ---")
suma = float(input("Введіть суму покупки: ")) # Сума може бути дробовою
if suma > 1000: # Якщо покупка більша за 1000 грн
    suma = suma * 0.95 # Рахуємо знижку 5% (множимо на 0.95)
elif suma > 500: # Інакше, якщо покупка більша за 500 грн
    suma = suma * 0.97 # Рахуємо знижку 3% (множимо на 0.97)
print(f"Сума зі знижкою: {suma:.2f} грн") # :.2f округлює суму до 2 знаків після коми

print("\n--- ЗАВДАННЯ 4 та 5 ---")
n1, n2, n3, n4 = 1, 2, 3, 4 # Задані 4 числа
min_val = min(n1, n2, n3, n4) # Функція min() шукає найменше значення
print(f"Косинус мінімального: {math.cos(min_val)}") # Знаходимо косинус
max_val = max(n1, n2, n3) # Функція max() шукає найбільше з перших трьох чисел
print(f"Синус максимального: {math.sin(max_val)}") # Знаходимо синус

print("\n--- ЗАВДАННЯ 6 ---")
base = float(input("Введіть основу трикутника: ")) # Ввід основи
height = float(input("Введіть висоту трикутника: ")) # Ввід висоти
area = 0.5 * base * height # Класична формула площі трикутника
# Перевіряємо, чи число ціле (остача від ділення на 1 дорівнює 0) і чи воно парне
if area % 1 == 0 and int(area) % 2 == 0: 
    print(f"Площа поділена на 2: {area / 2}") # Якщо так, ділимо на 2
else:
    print("Не можу ділити на 2!") # Якщо дробове або непарне

print("\n--- ЗАВДАННЯ 7 ---")
# Створюємо словник: зліва ключ (номер), справа значення (назва місяця)
months = {1: "January", 2: "February", 3: "March", 4: "April", 5: "May", 6: "June", 
          7: "July", 8: "August", 9: "September", 10: "October", 11: "November", 12: "December"}
m_num = int(input("Введіть номер місяця (1-12): ")) # Вводимо номер
