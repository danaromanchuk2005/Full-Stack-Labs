print("--- ЗАВДАННЯ 1 ---")
# Функція input() зупиняє програму і просить користувача ввести дані.
# Функція int() відразу перетворює введений текст на ціле число.
int_val1 = int(input("Введіть перше ціле число: "))
int_val2 = int(input("Введіть друге ціле число: "))
# Функція float() перетворює введений текст на дробове число (з крапкою).
float_val1 = float(input("Введіть перше дробове число: "))
float_val2 = float(input("Введіть друге дробове число: "))

print("\n--- ЗАВДАННЯ 2 ---")
# Створюємо список (квадратні дужки []), куди записуємо результати всіх операцій
results = [
    int_val1 + float_val1,   # додавання цілого і дробового чисел
    int_val1 - int_val2,     # віднімання двох цілих чисел
    float_val1 * float_val2, # множення двох дробових чисел
    int_val1 / int_val2,     # звичайне ділення (результат завжди дробовий)
    int_val1 ** 2,           # піднесення до ступеня (в даному випадку до квадрату)
    int_val1 // int_val2,    # цілочисленне ділення (відкидає дробову частину)
    int_val1 % int_val2      # остача від ділення
]
print("Всі результати дій додано у список.")

print("\n--- ЗАВДАННЯ 3 ---")
# Функція len() рахує загальну кількість елементів у нашому списку results
print(f"Кількість елементів у списку: {len(results)}")
print("Елементи списку з парними індексами:")
# Цикл for перебирає всі індекси від 0 до кінця списку
for i in range(len(results)):
    # Перевіряємо, чи є індекс парним (ділиться на 2 без остачі)
    if i % 2 == 0:
        # Якщо парний, виводимо його на екран разом із значенням
        print(f"Індекс {i}: {results[i]}")

print("\n--- ЗАВДАННЯ 4 ---")
# В Python нумерація йде з нуля. Тому 2-й елемент має індекс 1, а 5-й - індекс 4.
# Запис через кому дозволяє поміняти ці елементи місцями без додаткових змінних.
results[1], results[4] = results[4], results[1]
# Виводимо оновлений список (символ \n робить перехід на новий рядок)
print(f"Список після заміни 2-го та 5-го елементів:\n{results}")

print("\n--- ЗАВДАННЯ 5 ---")
# Зчитуємо текст з клавіатури (тут int/float не потрібні, бо це просто букви)
name = input("Введіть ваше прізвище та ім'я: ")
# Виводимо фінальне повідомлення з введеним іменем
print(f"Виконавець даної лабораторної роботи:\n{name}")