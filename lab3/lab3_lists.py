import random # Підключаємо модуль для генерації випадкових чисел

print("--- ЗАВДАННЯ 1 ---")
# Просимо користувача ввести числа через пробіл. 
# .split() розділяє введений текст по пробілах, а int() перетворює кожен шматочок на ціле число.
list1 = [int(x) for x in input("Введіть цілі числа через пробіл (наприклад: 5 12 -3 8): ").split()]
print(f"Максимальний елемент: {max(list1)}") # Знаходимо найбільше число за допомогою max()
# list1[::-1] створює копію списку у зворотному порядку
print(f"Список у зворотному порядку: {list1[::-1]}")

print("\n--- ЗАВДАННЯ 2 ---")
# Вводимо ще один список з клавіатури таким самим способом
list2 = [int(x) for x in input("Введіть числа для 2 завдання (наприклад: -5 10 0 22 -8): ").split()]
# Створюємо другий масив, вибираючи зі списку list2 тільки ті числа, які більші за 0 (додатні)
positive_list = [x for x in list2 if x > 0]
# Створюємо третій масив для решти чисел (менших або рівних 0)
other_list = [x for x in list2 if x <= 0]
print(f"Додатні елементи (другий масив): {positive_list}")
print(f"Решта елементів (третій масив): {other_list}")

print("\n--- ЗАВДАННЯ 3 ---")
# Генеруємо список із 20 випадкових цілих чисел у діапазоні від -50 до 50
list3 = [random.randint(-50, 50) for _ in range(20)]
print(f"Згенерований список довжиною 20:\n{list3}")
# Рахуємо суму. range(1, len(list3), 2) перебирає індекси: 1, 3, 5, 7... (непарні індекси)
sum_odd_idx = sum(list3[i] for i in range(1, len(list3), 2))
print(f"Сума елементів з непарними індексами: {sum_odd_idx}")

print("\n--- ЗАВДАННЯ 4 ---")
# Генеруємо список із 30 випадкових цілих чисел від -100 до 100
list4 = [random.randint(-100, 100) for _ in range(30)]
max_val4 = max(list4) # Знаходимо максимальний елемент
max_idx4 = list4.index(max_val4) # Знаходимо порядковий номер (індекс) цього максимального елемента
print(f"Максимальний елемент: {max_val4}, його номер (індекс): {max_idx4}")
# Відбираємо тільки непарні числа (остача від ділення на 2 не дорівнює 0)
odd_list4 = [x for x in list4 if x % 2 != 0]
if odd_list4: # Якщо список непарних чисел не порожній
    odd_list4.sort(reverse=True) # Сортуємо список у порядку зменшення
    print(f"Непарні числа в порядку зменшення:\n{odd_list4}")
else:
    print("Таких чисел (непарних) немає.")

print("\n--- ЗАВДАННЯ 5 ---")
# Генеруємо ще один список з 30 чисел від -100 до 100
list5 = [random.randint(-100, 100) for _ in range(30)]
print(f"Згенерований список:\n{list5}")
print("Пари від'ємних чисел, що стоять поруч:")
found_pair = False # Змінна-прапорець для перевірки, чи знайшли ми хоч одну пару
# Перебираємо всі елементи до передостаннього (щоб не вийти за межі списку при i+1)
for i in range(len(list5) - 1):
    # Якщо поточний елемент від'ємний І наступний теж від'ємний
    if list5[i] < 0 and list5[i+1] < 0:
        print(f"({list5[i]}, {list5[i+1]})")
        found_pair = True
if not found_pair:
    print("Таких пар немає.")

print("\n--- ЗАВДАННЯ 6 ---")
# Генеруємо список з 10 цілих чисел
list6 = [random.randint(-50, 50) for _ in range(10)]
print(f"Початковий список:\n{list6}")
max_val6 = max(list6) # Знаходимо максимальне число
print(f"Максимальний елемент: {max_val6}")
# Створюємо новий список. Беремо квадрат (x**2) для кожного числа, яке менше за максимальне
squares_list = [x**2 for x in list6 if x < max_val6]
squares_list.sort(reverse=True) # Сортуємо отримані квадрати за зменшенням
print(f"Квадрати менших чисел за зменшенням:\n{squares_list}")

print("\n--- ЗАВДАННЯ 7 ---")
# Генеруємо список з 30 дійсних (дробових) чисел. round(..., 2) залишає 2 знаки після коми
list7 = [round(random.uniform(-100, 100), 2) for _ in range(30)]
# Знаходимо мінімальний елемент за модулем за допомогою параметра key=abs
min_abs_val = min(list7, key=abs)
print(f"Мінімальний по модулю елемент: {min_abs_val}")
list7.sort() # Сортуємо список у порядку збільшення (зростання)
print(f"Список в порядку збільшення значення:\n{list7}")

print("\n--- ЗАВДАННЯ 8 ---")
# Генеруємо список з 30 дробових чисел
list8 = [round(random.uniform(-100, 100), 2) for _ in range(30)]
# Розбиваємо 30 елементів на 10 маленьких списків по 3 елементи за допомогою зрізів [i:i+3]
sublists = [list8[i:i+3] for i in range(0, 30, 3)]
# Сортуємо маленькі списки. key=lambda lst: sum(abs(x)... означає: "сортувати за сумою модулів елементів"
sublists.sort(key=lambda lst: sum(abs(x) for x in lst))
print("Відсортовані 10 списків по 3 елементи (за зростанням суми модулів):")
for sub in sublists:
    # Виводимо сам підсписок і поруч показуємо його суму модулів для перевірки
    print(f"{sub} (Сума модулів: {sum(abs(x) for x in sub):.2f})")